CREATE TABLE ASOP_GPS_TRACKING_2027_02 PARTITION OF ASOP_GPS_TRACKING FOR VALUES FROM ('2027-02-01') TO ('2027-03-01');
CREATE TABLE ASOP_GPS_TRACKING_2027_03 PARTITION OF ASOP_GPS_TRACKING FOR VALUES FROM ('2027-03-01') TO ('2027-04-01');

-- 4. API keys table
CREATE TABLE ASOP_API_KEYS
(
    KEY_ID      UUID         NOT NULL,
    KEY_VALUE   VARCHAR(128) NOT NULL,
    NAME        VARCHAR(100) NOT NULL,
    HMAC_SECRET VARCHAR(128) NOT NULL,
    IS_ACTIVE   BOOLEAN      DEFAULT true,
    RATE_LIMIT  INT          DEFAULT 60,
    CREATED_AT  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    DELETED_AT  TIMESTAMPTZ,
    CONSTRAINT pk_api_keys PRIMARY KEY (KEY_ID),
    CONSTRAINT uq_api_keys_value UNIQUE (KEY_VALUE)
);

COMMENT ON TABLE ASOP_API_KEYS IS 'API-ключи для публичных клиентов (пассажиры)';

